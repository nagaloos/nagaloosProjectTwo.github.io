import { useState } from 'react'
import './App.css'
import SearchBar from './SearchBar'

function App() {
  //CONTROLLED FORM COMPONENTS
  //useState stores the current value of each input
  //the empty string means each field starts blank
  const [name, setName] = useState("")
  const [email, setEmail] = useState("")
  const [phone, setPhone] = useState("")

  //store all contacts added
  //each contact will be an object inside this array
  const [contacts, setContacts] = useState([])

  //store text entered in search box
  const [searchText, setSearchText] = useState('')

  //these functions update state when the user types
  //e represents the event generated by the input
  //e.target.value contains the text currently in that input
  const handleNameChange = (e) => {
    setName(e.target.value)
  }

  const handleEmailChange = (e) => {
    setEmail(e.target.value)
  }

  const handlePhoneChange = (e) => {
    setPhone(e.target.value)
  }

  //prevent an empty form from being submitted
  const handleSubmit = (e) => {
    e.preventDefault()
    
    if (name == "" || email == "") {
      alert("You must enter a name and email address.")
      return
    }

    //basic email validity check
    if (!email.includes('@')) {
      alert("You must enter a valid email address.")
      return
    }

    //create an object containing the new contact's information
    const newContact = {
      id: Date.now().toString(), //use timestamp to generate ID
      name: name,
      email: email,
      phone: phone
    }

    //display added contacts
    setContacts([...contacts, newContact]) //... is the rest operator, which allows this function to display a variable amount of contacts

    //clear inputs after valid submission
    setName("")
    setEmail("")
    setPhone("")
  }

  //remove contact from the list by using ID to filter out the target
  const handleDelete = (id) => { //keep every contact except the one being deleted
  const updatedContacts = contacts.filter((contact) => { return contact.id != id })

  //update contact list after addition or deletion
  setContacts(updatedContacts)
}

//filter contacts by name or email
const filteredContacts = contacts.filter((contact) => {
  return ( //toLowerCase() makes searching case-insensitive, while includes() checks if what's being searched for exists
    contact.name.toLowerCase().includes(searchText.toLowerCase()) || contact.email.toLowerCase().includes(searchText.toLowerCase())
  )
})

  //you can add a contact using this form
  return (
    <main>
      <section className="contactForm">
      <h2>Add a Contact</h2>
      <form onSubmit={handleSubmit}>
      <div className="form">
        <label>Name</label>
        <input type="text" name="name" value={name} onChange={handleNameChange} />
      </div>

      <div className="form">
        <label>Email</label>
        <input type="email" name="email" value={email} onChange={handleEmailChange} />
      </div>

      <div className="form">
        <label>Phone</label>
        <input type="tel" name="phone" value={phone} onChange={handlePhoneChange} />
      </div>

      <button type="submit">Add Contact</button>
      </form>
    </section>

    <SearchBar searchText={searchText} setSearchText={setSearchText}/> {/* search bar takes whatever the user types into it */}

    <section className="contactSection">
        <h2>Your Contacts</h2>
        {/* a ternary comparison operation was used because a standard if-else one can't be directly inserted into JSX (https://www.w3schools.com/react/react_jsx_if_statements.asp) */}
        {contacts.length == 0 ? ( //show an empty message if there are no contacts
          <div className="emptyState">
            <h3>No contacts yet</h3>
            <p>Add one above!</p>
          </div>
        ) : filteredContacts.length == 0 ? ( //no contacts were found matching a search query
          <p>No matches found for "{searchText}"</p>
        ) : ( //this operation can have more than 3 parts
          //map() creates a displayed element for each contact
          <div className="contactList">
            {filteredContacts.map((contact) => ( //only display contacts that satisfy a search query (or all if there's none)
              <div className="contactCard" key={contact.id}>
                <h3>{contact.name}</h3>
                <p>Email: {contact.email}</p>
                <p>Phone: {contact.phone || "N/A"}</p> {/* this field is optional */}
                {/* delete this contact */}
                <button type="button" onClick={() => handleDelete(contact.id)}>Delete</button>
              </div>
            ))}
          </div>
        )}
      </section>
    </main>
  )
}

export default App
